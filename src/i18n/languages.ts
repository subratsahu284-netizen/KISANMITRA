// In-memory cache for dynamic translations of any custom or regional text
const dynamicTranslationCache: Record<string, Record<string, string>> = {};

export function getUIText(key: string, langCode: string): string {
  // 1. Direct dictionary match
  if (UI_TRANSLATIONS[langCode]?.[key]) {
    return UI_TRANSLATIONS[langCode][key];
  }

  // 2. Dynamic cache match
  if (dynamicTranslationCache[langCode]?.[key]) {
    return dynamicTranslationCache[langCode][key];
  }

  // 3. Fallback to English dictionary or key itself
  return UI_TRANSLATIONS.en?.[key] || key;
}

export function cacheTranslation(langCode: string, key: string, translated: string) {
  if (!dynamicTranslationCache[langCode]) {
    dynamicTranslationCache[langCode] = {};
  }
  dynamicTranslationCache[langCode][key] = translated;
}

